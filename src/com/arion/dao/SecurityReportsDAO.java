    // Create - Add new report
    public int addReport(SecurityReport report) {
        String sql = "INSERT INTO security_reports (report_name, report_type, report_date, " +
                     "status, content, generated_by, notes) " +
                     "VALUES (?, ?, ?, ?, ?, ?, ?)";
        
        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            
            System.out.println("[SecurityReportDAO] Adding report: " + report.getReportName());
            
            pstmt.setString(1, report.getReportName());
            pstmt.setString(2, report.getReportType());
            pstmt.setDate(3, new java.sql.Date(report.getReportDate().getTime()));
            pstmt.setString(4, report.getStatus());
            pstmt.setString(5, report.getContent());
            pstmt.setInt(6, report.getGeneratedBy());
            pstmt.setString(7, report.getNotes());
            
            int rowsAffected = pstmt.executeUpdate();
            
            if (rowsAffected > 0) {
                ResultSet rs = pstmt.getGeneratedKeys();
                if (rs.next()) {
                    int reportId = rs.getInt(1);
                    System.out.println("[SecurityReportDAO] Report added with ID: " + reportId);
                    return reportId;
                }
            }
            
        } catch (SQLException e) {
            System.err.println("[SecurityReportDAO] Error adding report: " + e.getMessage());
            e.printStackTrace();
        }
        
        return -1;
    }
    
    // Read - Get report by ID
    public SecurityReport getReportById(int reportId) {
        String sql = "SELECT r.*, u.full_name as generator_name, u2.full_name as reviewer_name " +
                     "FROM security_reports r " +
                     "LEFT JOIN users u ON r.generated_by = u.user_id " +
                     "LEFT JOIN users u2 ON r.reviewed_by = u2.user_id " +
                     "WHERE r.report_id = ?";
        
        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {
            
            pstmt.setInt(1, reportId);
            ResultSet rs = pstmt.executeQuery();
            
            if (rs.next()) {
                return extractReportFromResultSet(rs);
            }
            
        } catch (SQLException e) {
            System.err.println("[SecurityReportDAO] Error getting report by ID: " + e.getMessage());
        }
        
        return null;
    }
    
