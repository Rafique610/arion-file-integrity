    // Helper method to extract Report from ResultSet
    private SecurityReport extractReportFromResultSet(ResultSet rs) throws SQLException {
        SecurityReport report = new SecurityReport();
        report.setReportId(rs.getInt("report_id"));
        report.setReportName(rs.getString("report_name"));
        report.setReportType(rs.getString("report_type"));
        report.setReportDate(new java.util.Date(rs.getDate("report_date").getTime()));
        report.setStatus(rs.getString("status"));
        report.setContent(rs.getString("content"));
        report.setGeneratedBy(rs.getInt("generated_by"));
        report.setCreatedDate(rs.getTimestamp("created_date"));
        report.setNotes(rs.getString("notes"));
        
        // Reviewed fields (nullable)
        int reviewedBy = rs.getInt("reviewed_by");
        if (!rs.wasNull()) {
            report.setReviewedBy(reviewedBy);
        }
        
        Timestamp reviewedDate = rs.getTimestamp("reviewed_date");
        if (reviewedDate != null) {
            report.setReviewedDate(reviewedDate);
        }
        
        // Additional fields from JOINs
        report.setGeneratorName(rs.getString("generator_name"));
        report.setReviewerName(rs.getString("reviewer_name"));
        
        return report;
    }
